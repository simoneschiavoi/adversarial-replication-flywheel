def h2(text):
    return [Paragraph(text, S['h2']),
            HRFlowable(width='100%', thickness=0.7, color=ACCENT,
                       spaceBefore=0, spaceAfter=7)]


def caption(label, text):
    """Table/figure caption: Lato label, serif text (tables above, figures
    below — one convention for the whole appendix)."""
    ink = TEXT_PRIMARY.hexval().replace('0x', '#')
    return Paragraph(f'<font name="Lato-Bold" color="{ink}">{label}</font>'
                     f'\u2002{text}', S['caption'])


def embed(path, max_w, max_h=340):
    img = PILImage.open(path)
    w, h = img.size
    ratio = min(max_w / w, max_h / h, 1.0)
    return Image(path, width=w * ratio, height=h * ratio)


