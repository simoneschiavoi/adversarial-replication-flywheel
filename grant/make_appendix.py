def base_table_style(n_rows, bands=None):
    """Booktabs: ink top/bottom rules, a lighter rule under the head,
    hairlines between body rows — or, for long tables, light bands whose
    grouping carries information (``bands``: set of row indices to tint)."""
    st = [
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('LINEABOVE', (0, 0), (-1, 0), 0.9, TEXT_PRIMARY),
        ('LINEBELOW', (0, 0), (-1, 0), 0.5, TEXT_PRIMARY),
        ('LINEBELOW', (0, -1), (-1, -1), 0.9, TEXT_PRIMARY),
        ('LEFTPADDING', (0, 0), (-1, -1), 4),
        ('RIGHTPADDING', (0, 0), (-1, -1), 4),
        ('TOPPADDING', (0, 0), (-1, -1), 3),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
    ]
    if bands is None:
        if n_rows > 2:
            st.append(('LINEBELOW', (0, 1), (-1, -2), 0.25, RULE))
    else:
        for r in bands:
            st.append(('BACKGROUND', (0, r), (-1, r), ZEBRA))
    return TableStyle(st)


def TH(t, align='center'):
    if align == 'center':
        return Paragraph(t, S['th'])
    return Paragraph(t, ParagraphStyle(
        f'th_{align}', parent=S['th'],
        alignment=TA_LEFT if align == 'left' else TA_RIGHT))


def TD(t, left=False, right=False):
    return Paragraph(t, S['td_l'] if left else S['td_r'] if right
                     else S['td'])


