    headers = ['arm', 'r', 'mutation', 'value', 'Δ mean', '95% CI',
               'cost', 'verdict']
    nat = []
    for c in range(8):
        w = stringWidth(headers[c], S['th'].fontName, S['th'].fontSize)
        for row in ROUNDS:
            txt = str(row[c])
            font = 'LibSerif-Bold' if '<b>' in txt else 'LibSerif'
            txt = txt.replace('<b>', '').replace('</b>', '')
            w = max(w, stringWidth(txt, font, 8.0))
        nat.append(w + 8.0 + 2.5)
    scale = AVAIL_W / sum(nat)
