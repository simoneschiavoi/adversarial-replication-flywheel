def _sgn(x, nd=5):
    """Signed fixed-point with typographic minus (U+2212)."""
    return f"{x:+.{nd}f}".replace("-", "−")


def _ci(pair, nd=5):
    return f"[{_sgn(pair[0], nd)}, {_sgn(pair[1], nd)}]"


